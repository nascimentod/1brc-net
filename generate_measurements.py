def generate_measurement(station: tuple) -> str:
    """Generate a single measurement line for a station."""
    name, min_temp, max_temp = station
    # Generate temperature with one decimal place
    temp = round(random.uniform(min_temp, max_temp), 1)
    return f"{name};{temp}\n"


def generate_file(num_rows: int = 1_000_000_000, output_file: str = "measurements.txt"):
    """
    Generate the measurements file.
    
    Args:
        num_rows: Number of rows to generate (default 1 billion)
        output_file: Output filename
    """
    print(f"Generating {num_rows:,} measurements...")
    print(f"Output file: {output_file}")
    print(f"Using {len(STATIONS)} weather stations")
    
    # Use buffered writing for better performance
    BUFFER_SIZE = 1024 * 1024 * 10  # 10MB buffer
    
    with open(output_file, 'w', buffering=BUFFER_SIZE) as f:
        for i in range(num_rows):
            # Randomly select a station
            station = random.choice(STATIONS)
            f.write(generate_measurement(station))
            
            # Progress indicator every 10 million rows
            if (i + 1) % 10_000_000 == 0:
                progress = ((i + 1) / num_rows) * 100
                print(f"Progress: {i + 1:,} rows ({progress:.1f}%)")
    
    print(f"\nComplete! Generated {num_rows:,} measurements in {output_file}")


def main():
    import argparse
    
    parser = argparse.ArgumentParser(
        description="Generate measurements file for the One Billion Row Challenge"
    )
    parser.add_argument(
        "-n", "--rows",
        type=int,
        default=1_000_000_000,
        help="Number of rows to generate (default: 1,000,000,000)"
    )
    parser.add_argument(
        "-o", "--output",
        type=str,
        default="measurements.txt",
        help="Output filename (default: measurements.txt)"
    )
    
    args = parser.parse_args()
    
    # Validate input
    if args.rows < 1:
        print("Error: Number of rows must be at least 1")
        sys.exit(1)
    
    generate_file(args.rows, args.output)


if __name__ == "__main__":
    main()
